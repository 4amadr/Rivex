from __future__ import annotations

import os
from datetime import date
from typing import Any, Optional

import psycopg2
from dotenv import load_dotenv


class raw_vonix:
    """Persiste os dados raw (HTML bruto) do Vonix no schema ``dados_raw``."""

    def __init__(self, conexao_compartilhada: Optional[Any] = None) -> None:
        self._possui_conexao = conexao_compartilhada is None
        if conexao_compartilhada is not None:
            self.conexao = conexao_compartilhada.conexao
            self.cursor = conexao_compartilhada.cursor
        else:
            load_dotenv()
            self.conexao = psycopg2.connect(
                host=os.getenv("HOST_DB"),
                database=os.getenv("DATABASE_CONTECH"),
                user=os.getenv("USER_DB"),
                password=os.getenv("SENHA_DB"),
                port=os.getenv("PORT_DB") or 5432,
            )
            self.cursor = self.conexao.cursor()

        self._criar_tabelas()

    @staticmethod
    def _extrair_html(conteudo: Any) -> str:
        if conteudo is None:
            return ""
        texto = conteudo.text if hasattr(conteudo, "text") else conteudo
        return texto if isinstance(texto, str) else str(texto)

    def _executar(self, query: str, params: tuple[Any, ...] | None = None) -> None:
        try:
            if params is None:
                self.cursor.execute(query)
            else:
                self.cursor.execute(query, params)
            self.conexao.commit()
        except Exception:
            self.conexao.rollback()
            raise

    def _criar_tabelas(self) -> None:
        queries = [
            "CREATE SCHEMA IF NOT EXISTS dados_raw;",
            """
            CREATE TABLE IF NOT EXISTS dados_raw.dados_cliente_vonix (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                equipe TEXT NOT NULL,
                data DATE NOT NULL,
                queue_edit_html TEXT,
                calls_html TEXT,
                atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                UNIQUE (equipe, data)
            );
            """,
            """
            CREATE TABLE IF NOT EXISTS dados_raw.dados_operador_vonix (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                equipe TEXT NOT NULL,
                data DATE NOT NULL,
                agents_html TEXT,
                atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                UNIQUE (equipe, data)
            );
            """,
            """
            CREATE TABLE IF NOT EXISTS dados_raw.fila_vonix_raw (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                data DATE NOT NULL,
                queues_html TEXT,
                atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                UNIQUE (data)
            );
            """,
            "CREATE INDEX IF NOT EXISTS idx_dados_cliente_vonix_data ON dados_raw.dados_cliente_vonix (data);",
            "CREATE INDEX IF NOT EXISTS idx_dados_operador_vonix_data ON dados_raw.dados_operador_vonix (data);",
            "CREATE INDEX IF NOT EXISTS idx_fila_vonix_raw_data ON dados_raw.fila_vonix_raw (data);",
        ]
        try:
            for query in queries:
                self.cursor.execute(query)
            self.conexao.commit()
        except Exception:
            self.conexao.rollback()
            raise

    def enviar_cliente_raw(
        self,
        equipe: str,
        queue_edit_raw: Any,
        calls_raw: Any,
        data_coleta: date | None = None,
    ) -> None:
        data_ref = data_coleta or date.today()
        query = """
            INSERT INTO dados_raw.dados_cliente_vonix (
                equipe, data, queue_edit_html, calls_html, atualizado_em
            )
            VALUES (%s, %s, %s, %s, NOW())
            ON CONFLICT (equipe, data) DO UPDATE SET
                queue_edit_html = EXCLUDED.queue_edit_html,
                calls_html = EXCLUDED.calls_html,
                atualizado_em = NOW();
        """
        self._executar(
            query,
            (
                equipe,
                data_ref,
                self._extrair_html(queue_edit_raw),
                self._extrair_html(calls_raw),
            ),
        )

    def enviar_operador_raw(
        self,
        equipe: str,
        agents_raw: Any,
        data_coleta: date | None = None,
    ) -> None:
        data_ref = data_coleta or date.today()
        query = """
            INSERT INTO dados_raw.dados_operador_vonix (
                equipe, data, agents_html, atualizado_em
            )
            VALUES (%s, %s, %s, NOW())
            ON CONFLICT (equipe, data) DO UPDATE SET
                agents_html = EXCLUDED.agents_html,
                atualizado_em = NOW();
        """
        self._executar(query, (equipe, data_ref, self._extrair_html(agents_raw)))

    def enviar_fila_raw(
        self,
        queues_raw: Any,
        data_coleta: date | None = None,
    ) -> None:
        data_ref = data_coleta or date.today()
        query = """
            INSERT INTO dados_raw.fila_vonix_raw (
                data, queues_html, atualizado_em
            )
            VALUES (%s, %s, NOW())
            ON CONFLICT (data) DO UPDATE SET
                queues_html = EXCLUDED.queues_html,
                atualizado_em = NOW();
        """
        self._executar(query, (data_ref, self._extrair_html(queues_raw)))

    def enviar_dados_raw(
        self,
        equipe: str,
        dados_raw: dict[str, Any],
        queues_raw: Any = None,
        data_coleta: date | None = None,
    ) -> None:
        self.enviar_cliente_raw(
            equipe=equipe,
            queue_edit_raw=dados_raw.get("queue_edit"),
            calls_raw=dados_raw.get("calls"),
            data_coleta=data_coleta,
        )
        self.enviar_operador_raw(
            equipe=equipe,
            agents_raw=dados_raw.get("agents"),
            data_coleta=data_coleta,
        )
        if queues_raw is not None:
            self.enviar_fila_raw(queues_raw=queues_raw, data_coleta=data_coleta)

    def fechar(self) -> None:
        if self._possui_conexao:
            if getattr(self, "cursor", None):
                self.cursor.close()
            if getattr(self, "conexao", None):
                self.conexao.close()

    def __enter__(self) -> "raw_vonix":
        return self

    def __exit__(self, exc_type, exc_val, exc_tb) -> None:
        self.fechar()
